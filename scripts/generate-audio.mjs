#!/usr/bin/env node
/*
 * Generate every voice clip the app uses with an ElevenLabs voice
 * (for example, a clone of your own voice), and write audio/manifest.js.
 *
 *   ELEVENLABS_API_KEY=xxxx ELEVENLABS_VOICE_ID=yyyy node scripts/generate-audio.mjs
 *
 * Options:
 *   --force        re-generate clips that already exist
 *   --only=words   only one group: words | letters | sentences | phrases
 *   --list         print what would be generated, call nothing
 *
 * Already have your own recordings instead? Drop MP3s into audio/<group>/<name>.mp3
 * (names are printed by --list) and run:  node scripts/generate-audio.mjs --manifest
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const audioDir = path.join(root, "audio");
const args = new Set(process.argv.slice(2));
const only = [...args].find(a => a.startsWith("--only="))?.split("=")[1];

// Load the same data file the app uses.
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "js/words.js"), "utf8"), ctx);
const { SIGHT_WORDS, PHRASES } = ctx.window;
const slug = w => w.toLowerCase().replace(/[^a-z0-9]+/g, "");

// Build the clip list: [key, text]
const clips = [];
const words = new Map();
for (const set of SIGHT_WORDS) for (const item of set.words) {
  words.set(slug(item.word), item.word);
  item.sentences.forEach(([text], i) => {
    clips.push([`sentences/${slug(item.word)}-${i + 1}`, text]);
    // every word in a sentence is tappable, so give each one a clip too
    for (const t of text.split(/\s+/)) {
      const bare = t.replace(/[^A-Za-z'-]/g, "");
      if (bare && !words.has(slug(bare))) words.set(slug(bare), bare.toLowerCase());
    }
  });
}
for (const [k, w] of words) clips.push([`words/${k}`, `${w}.`]);
for (const l of "abcdefghijklmnopqrstuvwxyz") clips.push([`letters/${l}`, `${l.toUpperCase()}.`]);
for (const [k, text] of Object.entries(PHRASES)) clips.push([`phrases/${k}`, text]);

const todo = clips.filter(([k]) => !only || k.startsWith(only + "/"));

function writeManifest() {
  const have = clips.map(([k]) => k).filter(k => fs.existsSync(path.join(audioDir, k + ".mp3")));
  fs.writeFileSync(path.join(audioDir, "manifest.js"),
    "/* Auto-generated by scripts/generate-audio.mjs — lists recorded clips in /audio.\n" +
    "   Empty = the app uses the device's built-in voice. */\n" +
    `window.AUDIO_MANIFEST = ${JSON.stringify(have, null, 0)};\n`);
  console.log(`manifest: ${have.length}/${clips.length} clips available`);
}

if (args.has("--list")) {
  for (const [k, t] of todo) console.log(`${k}.mp3\t${t}`);
  console.log(`\n${todo.length} clips`);
  process.exit(0);
}
if (args.has("--manifest")) { writeManifest(); process.exit(0); }

const KEY = process.env.ELEVENLABS_API_KEY, VOICE = process.env.ELEVENLABS_VOICE_ID;
if (!KEY || !VOICE) {
  console.error("Set ELEVENLABS_API_KEY and ELEVENLABS_VOICE_ID (see README).");
  process.exit(1);
}
const MODEL = process.env.ELEVENLABS_MODEL || "eleven_multilingual_v2";

async function tts(text) {
  const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE}?output_format=mp3_44100_128`, {
    method: "POST",
    headers: { "xi-api-key": KEY, "Content-Type": "application/json", Accept: "audio/mpeg" },
    body: JSON.stringify({
      text,
      model_id: MODEL,
      // Warm and steady for little listeners; a touch slower than normal.
      voice_settings: { stability: 0.55, similarity_boost: 0.85, style: 0.15, use_speaker_boost: true, speed: 0.9 }
    })
  });
  if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
  return Buffer.from(await res.arrayBuffer());
}

let made = 0, skipped = 0;
const queue = todo.slice();
async function worker() {
  while (queue.length) {
    const [key, text] = queue.shift();
    const file = path.join(audioDir, key + ".mp3");
    if (fs.existsSync(file) && !args.has("--force")) { skipped++; continue; }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    for (let attempt = 1; ; attempt++) {
      try { fs.writeFileSync(file, await tts(text)); made++; console.log(`✓ ${key}  “${text}”`); break; }
      catch (e) {
        if (attempt >= 4) { console.error(`✗ ${key}: ${e.message}`); break; }
        await new Promise(r => setTimeout(r, 1500 * attempt));
      }
    }
  }
}
await Promise.all([worker(), worker(), worker()]);
console.log(`done: ${made} new, ${skipped} already there`);
writeManifest();
